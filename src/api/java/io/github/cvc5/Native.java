package io.github.cvc5;

import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;

import io.github.cvc5.capi.CApi;
import java.lang.foreign.Arena;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.invoke.MethodHandle;

/**
 * Helpers for calling the cvc5 C API through its bindings
 * ({@link io.github.cvc5.capi.CApi}, generated by jextract).
 *
 * <p>The C API reports errors through thread-local state, which it resets at
 * the beginning of each call: the caller checks it right after the call, on
 * the same thread. Every call of the C API is therefore wrapped in one of the
 * following, which raise an error as a Java exception:</p>
 * <ul>
 * <li>{@link #handle(MemorySegment)} for functions that return a handle
 *     ({@code Cvc5Term}, {@code Cvc5Sort}, ...), which is NULL on error;</li>
 * <li>{@link #string(MemorySegment)} and {@link #u32string(MemorySegment)}
 *     for functions that return a string, which is copied;</li>
 * <li>{@code check(...)} for functions that return anything else, and
 *     {@link #check()} after functions that return nothing.</li>
 * </ul>
 *
 * <p>Strings and arrays returned by the C API live in thread-local buffers
 * that are only valid until the next call of the same function, so they are
 * copied immediately.</p>
 */
final class Native
{
  private Native() {}

  static
  {
    Utils.loadLibraries();
  }

  /**
   * {@code cvc5_has_error()}, which runs after every C API call, as a
   * critical function: it only reads a thread-local flag, so it does not need
   * the thread state transitions of a regular downcall.
   */
  private static final MethodHandle HAS_ERROR =
      Linker.nativeLinker().downcallHandle(CApi.cvc5_has_error$address(),
          CApi.cvc5_has_error$descriptor(),
          Linker.Option.critical(false));

  /** Error kinds, see {@code Cvc5ErrorKind} in the C API. */
  private static final int ERROR_KIND_RECOVERABLE = 2;
  private static final int ERROR_KIND_OPTION = 3;
  private static final int ERROR_KIND_PARSER = 4;
  private static final int ERROR_KIND_OUT_OF_MEMORY = 5;

  /* .................................................................... */
  /* Errors                                                               */
  /* .................................................................... */

  /**
   * Raise the error of the most recent C API call on this thread, if any.
   *
   * <p>Errors are mapped to the exception types of the Java API according to
   * their kind. A parser error raises a {@link CVC5ParserException}, which is
   * a checked exception, regardless of whether the calling method declares
   * it, as native methods did when the Java API was based on JNI.</p>
   */
  static void check()
  {
    if (hasError())
    {
      int kind = CApi.cvc5_get_error_kind();
      String message = CApi.cvc5_get_error_message().reinterpret(Long.MAX_VALUE).getString(0);
      switch (kind)
      {
        case ERROR_KIND_OPTION: throw new CVC5ApiOptionException(message);
        case ERROR_KIND_RECOVERABLE: throw new CVC5ApiRecoverableException(message);
        case ERROR_KIND_PARSER:
          throw Native.<RuntimeException>sneaky(new CVC5ParserException(message));
        case ERROR_KIND_OUT_OF_MEMORY: throw new OutOfMemoryError(message);
        default: throw Callbacks.withCause(new CVC5ApiException(message), message);
      }
    }
  }

  private static boolean hasError()
  {
    try
    {
      return (boolean) HAS_ERROR.invokeExact();
    }
    catch (Error | RuntimeException e)
    {
      throw e;
    }
    catch (Throwable t)
    {
      throw new AssertionError("should not reach here", t);
    }
  }

  @SuppressWarnings("unchecked")
  private static <T extends Throwable> T sneaky(Throwable t) throws T
  {
    throw (T) t;
  }

  /**
   * Check the result of a C API function that returns a handle.
   *
   * @param result The handle returned by the function, which is NULL on error
   *               (and for null objects).
   * @return The handle.
   */
  static MemorySegment handle(MemorySegment result)
  {
    if (result.address() == 0)
    {
      check();
    }
    return result;
  }

  /**
   * Check the result of a C API function that returns a pointer other than a
   * handle or a string (e.g., an array).
   *
   * @param result The result of the function.
   * @return The result.
   */
  static MemorySegment check(MemorySegment result)
  {
    check();
    return result;
  }

  /**
   * Check the result of a C API function that returns a {@code bool}.
   *
   * @param result The result of the function.
   * @return The result.
   */
  static boolean check(boolean result)
  {
    check();
    return result;
  }

  /**
   * Check the result of a C API function that returns an {@code int}-sized
   * integer or an enum.
   *
   * @param result The result of the function.
   * @return The result.
   */
  static int check(int result)
  {
    check();
    return result;
  }

  /**
   * Check the result of a C API function that returns a {@code long}-sized
   * integer (e.g., {@code size_t}, {@code int64_t}, {@code uint64_t}).
   *
   * @param result The result of the function.
   * @return The result.
   */
  static long check(long result)
  {
    check();
    return result;
  }

  /**
   * Check the result of a C API function that returns a {@code double}.
   *
   * @param result The result of the function.
   * @return The result.
   */
  static double check(double result)
  {
    check();
    return result;
  }

  /* .................................................................... */
  /* Strings                                                              */
  /* .................................................................... */

  /**
   * Check the result of a C API function that returns a NUL-terminated UTF-8
   * string, and copy it.
   *
   * @param result The string returned by the function.
   * @return The string, or {@code null} if the function returned NULL.
   */
  static String string(MemorySegment result)
  {
    check();
    return copyString(result);
  }

  /**
   * Copy a NUL-terminated UTF-8 string that is not the result of a C API
   * function, e.g., an output parameter or a field of a struct.
   *
   * @param s The string.
   * @return The string, or {@code null} if {@code s} is NULL.
   */
  static String copyString(MemorySegment s)
  {
    return s.address() == 0 ? null : s.reinterpret(Long.MAX_VALUE).getString(0);
  }

  /**
   * Check the result of a C API function that returns a NUL-terminated UTF-32
   * string ({@code const char32_t*}), and copy it.
   *
   * @param result The string returned by the function.
   * @return The string.
   */
  static String u32string(MemorySegment result)
  {
    check();
    MemorySegment s = result.reinterpret(Long.MAX_VALUE);
    StringBuilder b = new StringBuilder();
    for (long i = 0;; i += Integer.BYTES)
    {
      int c = s.get(JAVA_INT, i);
      if (c == 0)
      {
        return b.toString();
      }
      b.appendCodePoint(c);
    }
  }

  /**
   * Copy an array of NUL-terminated UTF-8 strings ({@code const char**}).
   *
   * @param array The array.
   * @param size The number of strings.
   * @return The strings.
   */
  static String[] strings(MemorySegment array, long size)
  {
    MemorySegment[] pointers = handles(array, size);
    String[] res = new String[pointers.length];
    for (int i = 0; i < res.length; i++)
    {
      res[i] = copyString(pointers[i]);
    }
    return res;
  }

  /**
   * Allocate a NUL-terminated UTF-32 string ({@code const char32_t*}).
   *
   * @param arena The arena to allocate in.
   * @param s The string.
   * @return The native string.
   */
  static MemorySegment allocateU32String(Arena arena, String s)
  {
    int[] codePoints = s.codePoints().toArray();
    MemorySegment seg = arena.allocate(JAVA_INT, codePoints.length + 1);
    MemorySegment.copy(codePoints, 0, seg, JAVA_INT, 0, codePoints.length);
    return seg;
  }

  /**
   * Allocate an array of NUL-terminated UTF-8 strings ({@code const char**}).
   *
   * @param arena The arena to allocate in.
   * @param strings The strings.
   * @return The native array.
   */
  static MemorySegment allocateStrings(Arena arena, String[] strings)
  {
    MemorySegment[] pointers = new MemorySegment[strings.length];
    for (int i = 0; i < strings.length; i++)
    {
      pointers[i] = arena.allocateFrom(strings[i]);
    }
    return allocateHandles(arena, pointers);
  }

  /* .................................................................... */
  /* Arrays                                                               */
  /* .................................................................... */

  /**
   * Allocate an array of handles or other pointers.
   *
   * <p>The array is never NULL, even if it is empty, since the C API rejects
   * NULL arrays.</p>
   *
   * @param arena The arena to allocate in.
   * @param handles The handles.
   * @return The native array.
   */
  static MemorySegment allocateHandles(Arena arena, MemorySegment[] handles)
  {
    MemorySegment seg = arena.allocate(ADDRESS, Math.max(1, handles.length));
    for (int i = 0; i < handles.length; i++)
    {
      seg.setAtIndex(ADDRESS, i, handles[i]);
    }
    return seg;
  }

  /**
   * Allocate an array of {@code int}s (e.g., enum values or {@code uint32_t}s).
   *
   * <p>The array is never NULL, even if it is empty, since the C API rejects
   * NULL arrays.</p>
   *
   * @param arena The arena to allocate in.
   * @param values The values.
   * @return The native array.
   */
  static MemorySegment allocateInts(Arena arena, int[] values)
  {
    MemorySegment seg = arena.allocate(JAVA_INT, Math.max(1, values.length));
    MemorySegment.copy(values, 0, seg, JAVA_INT, 0, values.length);
    return seg;
  }

  /**
   * Copy an array of handles or other pointers.
   *
   * @param array The array (may be NULL if {@code size} is 0).
   * @param size The number of elements.
   * @return The handles.
   */
  static MemorySegment[] handles(MemorySegment array, long size)
  {
    MemorySegment[] res = new MemorySegment[Math.toIntExact(size)];
    if (size > 0)
    {
      MemorySegment seg = array.reinterpret(size * ADDRESS.byteSize());
      for (int i = 0; i < res.length; i++)
      {
        res[i] = seg.getAtIndex(ADDRESS, i);
      }
    }
    return res;
  }

  /**
   * Copy an array of {@code int}s.
   *
   * @param array The array (may be NULL if {@code size} is 0).
   * @param size The number of elements.
   * @return The values.
   */
  static int[] ints(MemorySegment array, long size)
  {
    if (size == 0)
    {
      return new int[0];
    }
    return array.reinterpret(size * JAVA_INT.byteSize()).toArray(JAVA_INT);
  }

  /**
   * Copy an array of 64-bit integers ({@code int64_t} or {@code uint64_t},
   * whose values are the same bits in a {@code long}).
   *
   * @param array The array (may be NULL if {@code size} is 0).
   * @param size The number of elements.
   * @return The values.
   */
  static long[] longs(MemorySegment array, long size)
  {
    if (size == 0)
    {
      return new long[0];
    }
    return array.reinterpret(size * JAVA_LONG.byteSize()).toArray(JAVA_LONG);
  }
}
